# Prueba rapida de la cadena: geometria -> UV -> horneado -> pintura -> render -> rig/clip -> export.
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
import importlib, ap_lib as A
importlib.reload(A)
import bpy, math

OUT = os.path.join(os.path.dirname(__file__), '..', '_prueba')
os.makedirs(OUT, exist_ok=True)
A.clean_scene()
C = A.collection('Mundo')
mb = A.MB('Cuerpo')
mb.box((0, 0, 0.4), (0.3, 1.2, 0.3), 'metal', bevel=0.03, edges='y')
mb.cyl((0, 0.6, 0.45), (0, 0.9, 0.45), 0.07, 8, 'metal', inset_cap1=0.02, inset_depth=0.05)
mb.prism([(-0.3, 0.25), (-0.1, 0.25), (-0.15, -0.3), (-0.4, -0.3)], -0.12, 0.12, 'poli', bevel=0.02)
cuerpo = mb.finish(C)
mb = A.MB('Pieza')
mb.box((0, -0.25, -0.1), (0.2, 0.25, 0.5), 'madera', bevel=0.02)
pieza = mb.finish(C, origin=(0, -0.25, 0.1))
objs = [cuerpo, pieza]
A.log('tris', A.tris(objs))
A.uv_unwrap(objs)
maps = A.bake_maps(objs, 512, R=1.5, ao_dist=0.25, bevel_r=0.03, samples=8, explode={pieza: (0, 0, -1.5)})
P = A.Paint(maps, R=1.5)
P.region('metal', '#3b3f44', var=0.10, stroke=(1, 4, 1), edge_col='#9aa3ab', edge=1.0, grime=0.3, rust=0.3)
P.region('poli', '#2d2a26', var=0.06)
P.region('madera', '#7a4a26', var=0.18, stroke=(1, 1, 6), tone_steps=4, edge_col='#b07a45', edge=0.8)
tex = os.path.join(OUT, 'prueba_color.png')
P.save(tex)
mat = A.final_material('M_Prueba', tex)
A.assign_final(objs, mat)
# rig y clip
arm = A.make_armature('Rig', [('Raiz', (0, 0, 0), None, 0.3), ('Pieza', (0, -0.25, 0.1), 'Raiz', 0.2)], C)
A.skin_rigid(cuerpo, arm, 'Raiz')
A.skin_rigid(pieza, arm, 'Pieza')
clip = A.Clip(arm, 'Disparo', 0.25)
clip.k('Pieza', 0.0).k('Pieza', 0.05, loc=(0, -0.2, 0), interp='LINEAR').k('Pieza', 0.25, loc=(0, 0, 0), interp='BEZIER')
act = clip.build(['Raiz', 'Pieza'])
clip2 = A.Clip(arm, 'Reposo', 1.0, loop=True)
clip2.k('Raiz', 0.5, rot=(2, 0, 0))
act2 = clip2.build(['Raiz', 'Pieza'])
A.log('acciones', [a.name for a in bpy.data.actions], 'slots', [len(getattr(a, 'slots', [])) for a in bpy.data.actions])
A.set_action(arm, act)
A.export_fbx(os.path.join(OUT, 'prueba_disparo.fbx'), [arm] + objs, anim=True)
A.export_fbx(os.path.join(OUT, 'prueba_todo.fbx'), [arm] + objs, anim=True, all_actions=True)
A.export_glb(os.path.join(OUT, 'prueba.glb'), objs)
# render
R = A.collection('Preview')
A.setup_world()
A.add_lights(R)
cam = A.camera(R, 'Cam', (1.6, -1.8, 1.2), (0, 0.1, 0.3), lens=50)
A.ruler(R, -0.8, 0.5, 6)
A.setup_render((640, 360), 'EEVEE', 16)
A.log('motor', bpy.context.scene.render.engine)
A.render(os.path.join(OUT, 'prueba_eevee.png'), cam)
A.setup_render((640, 360), 'CYCLES', 16)
A.render(os.path.join(OUT, 'prueba_cycles.png'), cam)
A.save_blend(os.path.join(OUT, 'prueba.blend'))
A.log('ok')
